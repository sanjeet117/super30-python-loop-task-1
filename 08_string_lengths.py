'''
Given

languages = ["Python", "Java", "C++", "JavaScript", "Go"]

Print every language along with its length.
'''
languages = ["Python", "Java", "C++", "JavaScript", "Go"]
for i in languages:
  print(f'the language is {i} and its length is {len(i)}')

# used loop for iterating each element in list and used len function to find length in loop